name = "Emmanuella"

# String methods
print(name.upper())
print(name.lower())
print(name.title())

# Length
print(len(name))

# Indexing
print(name[0])
print(name[1])
print(name[-1])
print(name[-2])

# Slicing
print(name[0:4])
print(name[2:6])
print(name[:3])
print(name[3:])

# Slicing with step
word = "Python"
print(word[0:6:2])
print(word[1:6:2])

# First and last name
first_name = "emmanuella"
last_name = "oluwaseun"

print(first_name.title() + " " + last_name.title())